// Development tool, not part of the app. Rasterises a-z and '-' from a TTF with fontdue and writes
// `src/glyphs.rs` for the app: alpha masks plus advances and kerning, so the app can compose any word of
// the EFF list at run time without a font rasteriser.
//
//   cargo run --release -- /path/to/Montserrat-Medium.ttf 24 ../../src/glyphs.rs

use std::fmt::Write as _;

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let (font_path, px, out) = (&args[1], args[2].parse::<f32>().unwrap(), &args[3]);
    let bytes = std::fs::read(font_path).unwrap();
    let font = fontdue::Font::from_bytes(bytes, fontdue::FontSettings::default()).unwrap();
    let line = font.horizontal_line_metrics(px).unwrap();
    let chars: Vec<char> = ('a'..='z').chain(['-']).collect();

    let mut s = String::new();
    writeln!(s, "// SPDX-License-Identifier: GPL-3.0-or-later AND OFL-1.1").unwrap();
    writeln!(s, "// Generated by tools/gen-glyphs from {} at {px} px. Do not edit.", std::path::Path::new(font_path).file_name().unwrap().to_string_lossy()).unwrap();
    writeln!(s, "// Montserrat is licensed under the SIL Open Font License 1.1.\n").unwrap();
    writeln!(s, "#[allow(dead_code)]\npub const FONT_PX: f32 = {px:.1};").unwrap();
    writeln!(s, "/// Distance from the top of the line to the baseline, and the line height, in pixels.").unwrap();
    writeln!(s, "pub const ASCENT: i32 = {};", line.ascent.ceil() as i32).unwrap();
    writeln!(s, "pub const LINE_HEIGHT: i32 = {};\n", (line.ascent - line.descent).ceil() as i32).unwrap();
    writeln!(s, "pub struct Glyph {{").unwrap();
    writeln!(s, "    pub ch: char,").unwrap();
    writeln!(s, "    pub width: usize,").unwrap();
    writeln!(s, "    pub height: usize,").unwrap();
    writeln!(s, "    /// Offset of the mask's left edge from the pen position.").unwrap();
    writeln!(s, "    pub left: i32,").unwrap();
    writeln!(s, "    /// Height of the mask's top edge above the baseline.").unwrap();
    writeln!(s, "    pub top: i32,").unwrap();
    writeln!(s, "    pub advance: f32,").unwrap();
    writeln!(s, "    /// Coverage, row by row from the top, 0..=255.").unwrap();
    writeln!(s, "    pub mask: &'static [u8],").unwrap();
    writeln!(s, "}}\n").unwrap();
    writeln!(s, "pub static GLYPHS: [Glyph; {}] = [", chars.len()).unwrap();
    for &ch in &chars {
        let (m, bmp) = font.rasterize(ch, px);
        write!(s, "    Glyph {{ ch: {ch:?}, width: {}, height: {}, left: {}, top: {}, advance: {:.3}, mask: &[", m.width, m.height, m.xmin, m.ymin + m.height as i32, m.advance_width).unwrap();
        for (i, b) in bmp.iter().enumerate() {
            if i > 0 { s.push(','); }
            write!(s, "{b}").unwrap();
        }
        writeln!(s, "] }},").unwrap();
    }
    writeln!(s, "];\n").unwrap();
    writeln!(s, "/// Kerning between pairs, in pixels (only the pairs the font adjusts).").unwrap();
    let mut kern = Vec::new();
    for &a in &chars {
        for &b in &chars {
            if let Some(k) = font.horizontal_kern(a, b, px) {
                if k.abs() > 0.01 { kern.push((a, b, k)); }
            }
        }
    }
    writeln!(s, "pub static KERN: [(char, char, f32); {}] = [", kern.len()).unwrap();
    for (a, b, k) in &kern { writeln!(s, "    ({a:?}, {b:?}, {k:.3}),").unwrap(); }
    writeln!(s, "];").unwrap();
    std::fs::write(out, s).unwrap();
    eprintln!("wrote {out}: {} glyphs, {} kerning pairs, ascent {}, line {}", chars.len(), kern.len(), line.ascent.ceil(), (line.ascent - line.descent).ceil());
}
